    @Override
    public void setupAnim(GarrisonGolemEntity golem, float limbSwing, float limbSwingAmount, float ageInTicks,
                          float netHeadYaw, float headPitch) {
        root.getAllParts().forEach(ModelPart::resetPose);
        float partial = ageInTicks - golem.tickCount;
        float run = golem.runAmount(partial);
        float aim = golem.aimAmount(partial);
        float crank = golem.crankAmount(partial);
        float tinker = golem.tinkerAmount(partial);

        head.yRot = netHeadYaw * Mth.DEG_TO_RAD;
        head.xRot = headPitch * Mth.DEG_TO_RAD;

        // The march: stiff legs from the hip, the hips dipping as they swing
        // out, a toy's side-to-side waddle. Running bends the knees and elbows.
        float phase = limbSwing * 0.6662f;
        float amount = Math.min(limbSwingAmount, 1.0f);
        float swing = Mth.cos(phase) * amount * Mth.lerp(run, 0.75f, 1.0f);
        float knee = amount * Mth.lerp(run, 0.25f, 1.2f);
        rightLeg.xRot = swing;
        leftLeg.xRot = -swing;
        rightShin.xRot = Math.max(0.0f, Mth.sin(phase)) * knee;
        leftShin.xRot = Math.max(0.0f, -Mth.sin(phase)) * knee;
        float dip = LEG_LENGTH * (1.0f - Mth.cos(swing)) * Mth.lerp(run, 0.8f, 0.5f);
        body.y += dip;
        rightLeg.y += dip;
        leftLeg.y += dip;
        body.zRot = Mth.sin(phase) * 0.07f * amount * (1.0f - run);
        body.yRot = Mth.cos(phase) * 0.08f * amount;
        body.xRot = 0.3f * run;
        head.xRot -= 0.22f * run;

        float armSwing = swing * Mth.lerp(run, 0.8f, 1.1f);
        rightArm.xRot = -armSwing;
        leftArm.xRot = armSwing;
        rightForearm.xRot = -0.15f * amount - 1.0f * run;
        leftForearm.xRot = -0.15f * amount - 1.0f * run;

        // Standing still, it ticks: the head twitches each half-second.
        float still = (1.0f - amount) * (1.0f - aim) * (1.0f - tinker);
        float tock = ((int) (ageInTicks / 10.0f) & 1) == 0 ? 1.0f : -1.0f;
        head.zRot += tock * 0.035f * still;

        float spin = golem.keyAngle(partial);
        keyBow.zRot = spin;
        heart.zRot = -spin * 0.75f;

        if (tinker > 0.0f) {
            body.xRot += 0.25f * tinker;
            head.xRot += 0.35f * tinker;
            head.zRot += Mth.sin(ageInTicks * 0.05f) * 0.15f * tinker;
            rightArm.xRot = Mth.lerp(tinker, rightArm.xRot, -1.0f);
            leftArm.xRot = Mth.lerp(tinker, leftArm.xRot, -0.9f);
            rightArm.yRot = Mth.lerp(tinker, rightArm.yRot, -0.25f);
            leftArm.yRot = Mth.lerp(tinker, leftArm.yRot, 0.25f);
            rightForearm.xRot = Mth.lerp(tinker, rightForearm.xRot, -0.9f + Mth.sin(ageInTicks * 0.8f) * 0.25f);
            leftForearm.xRot = Mth.lerp(tinker, leftForearm.xRot, -0.8f + Mth.sin(ageInTicks * 0.6f + 1.0f) * 0.2f);
        }

        if (aim > 0.0f) {
            // Both hands out to the crossbow's stock; the left one steadies it.
            body.xRot += 0.1f * aim;
            rightArm.xRot = Mth.lerp(aim, rightArm.xRot, -1.62f);
            rightArm.yRot = Mth.lerp(aim, rightArm.yRot, -0.22f);
            rightForearm.xRot = Mth.lerp(aim, rightForearm.xRot, -0.05f);
            leftArm.xRot = Mth.lerp(aim, leftArm.xRot, -1.4f);
            leftArm.yRot = Mth.lerp(aim, leftArm.yRot, 0.38f);
            leftForearm.xRot = Mth.lerp(aim, leftForearm.xRot, -0.3f);
        }

        if (crank > 0.0f) {
            // The right hand works the reload crank round and round.
            float turn = ageInTicks * 0.7f;
            rightArm.xRot = Mth.lerp(crank, rightArm.xRot, -1.1f + Mth.sin(turn) * 0.35f);
            rightArm.zRot = Mth.lerp(crank, rightArm.zRot, Mth.cos(turn) * 0.22f);
            rightForearm.xRot = Mth.lerp(crank, rightForearm.xRot, -0.9f + Mth.cos(turn) * 0.35f);
            body.y += Mth.sin(turn * 2.0f) * 0.15f * crank;
        }

        float recoil = golem.recoilAmount(partial);
        if (recoil > 0.0f) {
            body.xRot -= 0.18f * recoil;
            head.xRot -= 0.1f * recoil;
            rightArm.xRot += 0.25f * recoil;
            leftArm.xRot += 0.25f * recoil;
        }

        float flinch = golem.flinchAmount(partial);
        if (flinch > 0.0f) {
            // Arms up over its face, ducking away.
            body.xRot -= 0.3f * flinch;
            body.y += 1.0f * flinch;
            head.xRot += 0.3f * flinch;
            rightArm.xRot = Mth.lerp(flinch, rightArm.xRot, -2.3f);
            leftArm.xRot = Mth.lerp(flinch, leftArm.xRot, -2.3f);
            rightArm.yRot = Mth.lerp(flinch, rightArm.yRot, -0.5f);
            leftArm.yRot = Mth.lerp(flinch, leftArm.yRot, 0.5f);
            rightForearm.xRot = Mth.lerp(flinch, rightForearm.xRot, -1.2f);
            leftForearm.xRot = Mth.lerp(flinch, leftForearm.xRot, -1.2f);
        }

        float salute = golem.saluteAmount(partial);
        if (salute > 0.0f) {
            rightArm.xRot = Mth.lerp(salute, rightArm.xRot, SALUTE_ARM_X);
            rightArm.yRot = Mth.lerp(salute, rightArm.yRot, SALUTE_ARM_Y);
            rightArm.zRot = Mth.lerp(salute, rightArm.zRot, SALUTE_ARM_Z);
            rightForearm.xRot = Mth.lerp(salute, rightForearm.xRot, SALUTE_FOREARM_X);
            rightForearm.zRot = Mth.lerp(salute, rightForearm.zRot, SALUTE_FOREARM_Z);
            head.xRot = Mth.lerp(salute, head.xRot, -0.05f);
            body.xRot = Mth.lerp(salute, body.xRot, -0.04f);
        }

        float shrug = golem.shrugAmount(partial);
        if (shrug > 0.0f) {
            // Out of bolts: a shake of the head and empty hands.
            head.yRot += Mth.sin(ageInTicks * 1.4f) * 0.45f * shrug;
            rightArm.zRot += 0.35f * shrug;
            leftArm.zRot -= 0.35f * shrug;
            rightForearm.xRot = Mth.lerp(shrug, rightForearm.xRot, -1.1f);
            leftForearm.xRot = Mth.lerp(shrug, leftForearm.xRot, -1.1f);
        }
    }

